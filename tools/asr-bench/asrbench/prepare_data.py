"""Download the public test sets and write seeded subsets as manifests.

Every set lands in $WORK/data/<set>/manifest.jsonl, one utterance per line:
{"id", "audio" (path), "text" (reference), "lang"}. Subsets are drawn with
random.Random(SEED), so a rerun picks the same utterances.

    python -m asrbench.prepare_data --work $WORK [sets...]

Sets and licenses (all fetched without an account):
  ls-clean, ls-other  LibriSpeech test-clean / test-other, 200 each (CC-BY-4.0, openslr.org)
  fleurs-en           FLEURS en_us test, 200 (CC-BY-4.0, google/fleurs)
  fleurs-es/de/fr     FLEURS es_419 / de_de / fr_fr test, 50 each (CC-BY-4.0)
  fleurs-ja/zh/ko     FLEURS ja_jp / cmn_hans_cn / ko_kr test, 200 / 100 / 100 (CC-BY-4.0; #29)
  fleurs-hi/ar/tr/vi/nb  FLEURS hi_in / ar_eg / tr_tr / vi_vn / nb_no test, 100 each (CC-BY-4.0; #37)
  fleurs-it/pt        FLEURS it_it / pt_br test, 100 each (CC-BY-4.0; #64: the last two UI languages)
  vox-de/es/fr/it/en  VoxPopuli test (European Parliament speeches, CC0, facebook/voxpopuli), 100
                      one-sentence segments each (#64: spontaneous pauses outside English)
  ami-ihm             AMI meeting corpus, individual headset mics, test split,
                      200 utterances of >= 2 s and >= 4 words (CC-BY-4.0, edinburghcstr/ami)
  ami-long            the same, 200 utterances of >= 8 s (#43: pauses inside a turn)
  ami-multi           200 turns of 2+ sentences, 8-20 s, joined from contiguous segments (#43)
  aishell1            AISHELL-1 test (20 speakers), 200 utterances (Apache-2.0, openslr.org SLR33; files
                      from the ungated per-file mirror shenyunhang/AISHELL-1 at a pinned revision, #29)
  zeroth-ko           Zeroth-Korean test, 100 utterances (CC-BY-4.0, openslr.org SLR40, via kresnik/zeroth_korean, #29)
  kokoro-speech-ja    Kokoro Speech Dataset (kaiidams, public domain): one LibriVox reader of 14
                      Meiji-Showa novels from Aozora Bunko, automatically aligned; 200 clips (#52)
Common Voice is not here: see README.md. JSUT/JVS audio is non-commercial, and
ReazonSpeech is gated and limited to Article 30-4 analysis (see README.md).
The dictation and noise sets are generated by make_synthetic.py.
"""

import argparse
import csv
import json
import random
import re
import tarfile
import urllib.request
from pathlib import Path

SEED = 14
HF = "https://huggingface.co/datasets"
# Pinned 2026-09-28 (each dataset repo's head commit on that date).
FLEURS_REV = "70bb2e84b976b7e960aa89f1c648e09c59f894dd"
AMI_REV = "46f28f2503e2ec48f8867a84eef356c70476beab"
AISHELL_REPO, AISHELL_REV = "shenyunhang/AISHELL-1", "2724409d538167445e43ebf846990319f12a1cbf"
AISHELL_TEST_SPEAKERS = [f"S0{n}" for n in [*range(764, 771), *range(901, 909), *range(912, 917)]]
ZEROTH_REPO, ZEROTH_REV = "kresnik/zeroth_korean", "1fe937899f828af822293d05e086200946088bdf"
KSD_ZIP = "https://github.com/kaiidams/Kokoro-Speech-Dataset/releases/download/1.3/kokoro-speech-v1_3.zip"
KSD_ZIP_SHA256 = "5a4a290672016ebe70372ed3d47063f846d86e2b96aa9e9b9d35161670d9f666"
VOXPOPULI_REV = "42f01879c780b4a2e90ec0b4f616c2ece526e4f1"  # pinned 2026-10-04 (#64)
# A sentence end with more text after it: . ! ? before a space, or a CJK / Devanagari / Arabic
# end mark anywhere but last. Abbreviations ("Dr. X") count too, which only drops a clip.
_INNER_SENTENCE_END = re.compile(r"[.!?](?=\s+\S)|[。！？।؟](?=.)")
_QUOTES = "\"'“”«»„ "


def one_sentence(text: str) -> bool:
    """No sentence ends before the text's last word: every pause inside it is mid-sentence (#64)."""
    return not _INNER_SENTENCE_END.search(text.strip(_QUOTES))


def download(url: str, dest: Path) -> Path:
    if not dest.exists():
        dest.parent.mkdir(parents=True, exist_ok=True)
        part = dest.with_name(dest.name + ".part")
        print(f"download {url}", flush=True)
        with urllib.request.urlopen(url) as r, part.open("wb") as w:
            while chunk := r.read(1 << 20):
                w.write(chunk)
        part.rename(dest)
    return dest


def write_manifest(out: Path, rows: list[dict]) -> None:
    out.mkdir(parents=True, exist_ok=True)
    with (out / "manifest.jsonl").open("w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{out.name}: {len(rows)} utterances", flush=True)


def librispeech(work: Path, name: str, n: int = 200) -> None:
    split = {"ls-clean": "test-clean", "ls-other": "test-other"}[name]
    raw = work / "raw" / "librispeech"
    tgz = download(f"https://www.openslr.org/resources/12/{split}.tar.gz", raw / f"{split}.tar.gz")
    root = raw / "LibriSpeech" / split
    if not root.exists():
        with tarfile.open(tgz) as t:
            t.extractall(raw, filter="data")
    utts = []
    for trans in sorted(root.glob("*/*/*.trans.txt")):
        for line in trans.read_text().splitlines():
            uid, text = line.split(" ", 1)
            utts.append({"id": uid, "audio": str(trans.parent / f"{uid}.flac"), "text": text, "lang": "en"})
    write_manifest(work / "data" / name, random.Random(SEED).sample(utts, n))


def fleurs(work: Path, name: str) -> None:
    lang = name.split("-")[1]
    config = {"en": "en_us", "es": "es_419", "de": "de_de", "fr": "fr_fr",
              "ja": "ja_jp", "zh": "cmn_hans_cn", "ko": "ko_kr",
              "hi": "hi_in", "ar": "ar_eg", "tr": "tr_tr", "vi": "vi_vn", "nb": "nb_no",
              "it": "it_it", "pt": "pt_br"}[lang]
    # CER sets (#29): Japanese has no second permissive set, so FLEURS-ja gets 200.
    n = 200 if lang in ("en", "ja") else 50 if lang in ("es", "de", "fr") else 100
    raw = work / "raw" / "fleurs" / config
    base = f"{HF}/google/fleurs/resolve/{FLEURS_REV}/data/{config}"
    tsv = download(f"{base}/test.tsv", raw / "test.tsv")
    tgz = download(f"{base}/audio/test.tar.gz", raw / "test.tar.gz")
    audio_dir = raw / "test"
    if not audio_dir.exists():
        with tarfile.open(tgz) as t:
            t.extractall(raw, filter="data")
    utts = []
    with tsv.open(newline="") as f:
        for row in csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            # id, file name, raw transcription (cased, punctuated), normalised, ...
            utts.append({"id": row[1].removesuffix(".wav"), "audio": str(audio_dir / row[1]),
                         "text": row[2], "lang": lang})
    write_manifest(work / "data" / name, random.Random(SEED).sample(utts, n))


def ami(work: Path, name: str = "ami-ihm", min_seconds: float = 2.0, n: int = 200) -> None:
    """AMI headset test utterances of >= `min_seconds` and >= 4 words. `ami-long` (#43) keeps
    the >= 8 s ones: long spontaneous turns with pauses inside, for the end-of-turn gate."""
    import pyarrow.parquet as pq

    raw = work / "raw" / "ami"
    audio_dir = raw / "ihm-test"
    audio_dir.mkdir(parents=True, exist_ok=True)
    utts = []
    for i in range(4):
        shard = download(f"{HF}/edinburghcstr/ami/resolve/{AMI_REV}/ihm/test-0000{i}-of-00004.parquet",
                         raw / f"test-{i}.parquet")
        table = pq.read_table(shard, columns=["audio_id", "text", "begin_time", "end_time"])
        for r in table.to_pylist():
            if r["end_time"] - r["begin_time"] >= min_seconds and len(r["text"].split()) >= 4:
                utts.append({"id": r["audio_id"], "shard": i, "text": r["text"], "lang": "en"})
    picked = random.Random(SEED).sample(sorted(utts, key=lambda u: u["id"]), n)
    want = {u["id"] for u in picked}
    for i in range(4):
        table = pq.read_table(raw / f"test-{i}.parquet", columns=["audio_id", "audio"])
        for r in table.to_pylist():
            if r["audio_id"] in want:
                (audio_dir / f"{r['audio_id']}.wav").write_bytes(r["audio"]["bytes"])
    rows = [{"id": u["id"], "audio": str(audio_dir / f"{u['id']}.wav"), "text": u["text"], "lang": "en"}
            for u in picked]
    write_manifest(work / "data" / name, rows)


def voxpopuli(work: Path, name: str, n: int = 100) -> None:
    """VoxPopuli test segments (#64): European Parliament speeches, mostly spontaneous or
    half-read, with real hesitation pauses. Keeps gold transcripts that are one whole sentence
    (capitalised, ending in . ? or !, no sentence end inside), so every pause is mid-sentence."""
    import pyarrow.parquet as pq

    lang = name.split("-")[1]
    raw = work / "raw" / "voxpopuli" / lang
    shard = download(f"{HF}/facebook/voxpopuli/resolve/{VOXPOPULI_REV}/{lang}/test-00000-of-00001.parquet",
                     raw / "test.parquet")
    rows = pq.read_table(shard, columns=["audio_id", "raw_text", "is_gold_transcript"]).to_pylist()
    utts = sorted((r for r in rows if r["is_gold_transcript"] and r["raw_text"][:1].isupper()
                   and r["raw_text"].rstrip()[-1:] in ".?!" and one_sentence(r["raw_text"])),
                  key=lambda r: r["audio_id"])
    picked = random.Random(SEED).sample(utts, n)
    want = {r["audio_id"] for r in picked}
    audio_dir = raw / "test"
    audio_dir.mkdir(parents=True, exist_ok=True)
    for r in pq.read_table(shard, columns=["audio_id", "audio"]).to_pylist():
        if r["audio_id"] in want:
            (audio_dir / f"{r['audio_id']}.wav").write_bytes(r["audio"]["bytes"])
    write_manifest(work / "data" / name, [{"id": r["audio_id"], "audio": str(audio_dir / f"{r['audio_id']}.wav"),
                                           "text": r["raw_text"], "lang": lang} for r in picked])


def write_float_wav(path: Path, samples, sample_rate: int = 16_000) -> None:
    """Mono IEEE-float WAV (format 3), as the AMI parquet stores its audio."""
    import struct

    data = samples.astype("<f4").tobytes()
    fmt = struct.pack("<HHIIHHH", 3, 1, sample_rate, sample_rate * 4, 4, 32, 0)
    fact = struct.pack("<I", len(samples))
    body = (b"WAVE" + b"fmt " + struct.pack("<I", len(fmt)) + fmt + b"fact" + struct.pack("<I", 4) + fact
            + b"data" + struct.pack("<I", len(data)) + data)
    path.write_bytes(b"RIFF" + struct.pack("<I", len(body)) + body)


def ami_multi(work: Path, n: int = 200, min_seconds: float = 8.0, max_seconds: float = 20.0) -> None:
    """AMI turns of two or more sentences (#43). The corpus's segments are one sentence each, and
    about 40 % of a speaker's consecutive segments are contiguous (the next starts where the last
    ended), so joining a run of contiguous segments rebuilds that speaker's real audio across the
    sentence ends. Each run gives one clip: its first segments, 8-20 s in total. Clip ids have the
    usual form (first begin, last end), so `ami_words` finds their words."""
    from collections import defaultdict

    import miniaudio
    import numpy as np
    import pyarrow.parquet as pq

    raw = work / "raw" / "ami"
    audio_dir = raw / "ihm-test-multi"
    audio_dir.mkdir(parents=True, exist_ok=True)
    by_channel = defaultdict(list)
    for i in range(4):
        shard = download(f"{HF}/edinburghcstr/ami/resolve/{AMI_REV}/ihm/test-0000{i}-of-00004.parquet",
                         raw / f"test-{i}.parquet")
        for r in pq.read_table(shard, columns=["audio_id", "meeting_id", "microphone_id", "speaker_id", "text",
                                               "begin_time", "end_time"]).to_pylist():
            by_channel[(r["meeting_id"], r["microphone_id"])].append(r)
    runs = []
    for key in sorted(by_channel):
        segs = sorted(by_channel[key], key=lambda r: r["begin_time"])
        run = [segs[0]]
        for seg in segs[1:] + [None]:
            if seg is not None and seg["begin_time"] - run[-1]["end_time"] < 0.01:
                run.append(seg)
                continue
            picked = []
            for r in run:
                if r["end_time"] - run[0]["begin_time"] > max_seconds:
                    break
                picked.append(r)
            if len(picked) >= 2 and picked[-1]["end_time"] - picked[0]["begin_time"] >= min_seconds:
                runs.append(picked)
            run = [seg]
    picked = random.Random(SEED).sample(runs, min(n, len(runs)))
    want = {r["audio_id"] for run in picked for r in run}
    audio = {}
    for i in range(4):
        for r in pq.read_table(raw / f"test-{i}.parquet", columns=["audio_id", "audio"]).to_pylist():
            if r["audio_id"] in want:
                d = miniaudio.decode(r["audio"]["bytes"], output_format=miniaudio.SampleFormat.FLOAT32, nchannels=1,
                                     sample_rate=16_000)
                audio[r["audio_id"]] = np.asarray(d.samples, dtype=np.float32)
    rows = []
    for run in picked:
        first, last = run[0], run[-1]
        uid = (f"AMI_{first['meeting_id']}_{first['microphone_id']}_{first['speaker_id']}"
               f"_{round(first['begin_time'] * 100):07d}_{round(last['end_time'] * 100):07d}")
        dest = audio_dir / f"{uid}.wav"
        if not dest.exists():
            write_float_wav(dest, np.concatenate([audio[r["audio_id"]] for r in run]))
        rows.append({"id": uid, "audio": str(dest), "text": " ".join(r["text"] for r in run), "lang": "en"})
    write_manifest(work / "data" / "ami-multi", rows)


def aishell1(work: Path, n: int = 200) -> None:
    """AISHELL-1 test: the whole corpus is one 15 GB tarball, so fetch the sampled files one by one."""
    raw = work / "raw" / "aishell1"
    base = f"{HF}/{AISHELL_REPO}/resolve/{AISHELL_REV}/data_aishell"
    trans = download(f"{base}/transcript/aishell_transcript_v0.8.txt", raw / "aishell_transcript_v0.8.txt")
    # Word-segmented with spaces, no punctuation, numbers spelled out.
    text = dict(line.split(" ", 1) for line in trans.read_text(encoding="utf-8").splitlines() if " " in line)
    listing = raw / "test-files.json"
    if not listing.exists():
        files = {}
        for spk in AISHELL_TEST_SPEAKERS:
            api = f"https://huggingface.co/api/datasets/{AISHELL_REPO}/tree/{AISHELL_REV}/data_aishell/wav/test/{spk}"
            with urllib.request.urlopen(api) as r:
                for item in json.load(r):
                    files[Path(item["path"]).stem] = item["path"]
        listing.write_text(json.dumps(files, indent=0, sort_keys=True))
    files = json.loads(listing.read_text())
    ids = sorted(i for i in files if i in text)
    rows = []
    for uid in random.Random(SEED).sample(ids, n):
        dest = download(f"{HF}/{AISHELL_REPO}/resolve/{AISHELL_REV}/{files[uid]}", raw / "test" / f"{uid}.wav")
        rows.append({"id": uid, "audio": str(dest), "text": text[uid].replace(" ", "").strip(), "lang": "zh"})
    write_manifest(work / "data" / "aishell1", rows)


def zeroth(work: Path, n: int = 100) -> None:
    import pyarrow.parquet as pq

    raw = work / "raw" / "zeroth-ko"
    shard = download(f"{HF}/{ZEROTH_REPO}/resolve/{ZEROTH_REV}/data/test-00000-of-00001.parquet", raw / "test.parquet")
    table = pq.read_table(shard, columns=["id", "text", "audio"]).to_pylist()
    rows = []
    for r in random.Random(SEED).sample(sorted(table, key=lambda r: r["id"]), n):
        ext = Path(r["audio"].get("path") or "x.flac").suffix or ".flac"
        dest = raw / "test" / f"{r['id']}{ext}"
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(r["audio"]["bytes"])
        # No punctuation, numbers spelled out.
        rows.append({"id": r["id"], "audio": str(dest), "text": r["text"], "lang": "ko"})
    write_manifest(work / "data" / "zeroth-ko", rows)


def kokoro_speech(work: Path, n: int = 200) -> None:
    """Kokoro Speech Dataset v1.3 (#52): a seeded sample over all 14 books. The release holds only
    metadata (per book: clip id, LibriVox MP3 file, start and end sample at 22.05 kHz, Aozora text,
    reading); the clips are cut from LibriVox's MP3s on archive.org, fetched one file at a time."""
    import hashlib
    import zipfile

    import miniaudio
    import numpy as np

    raw = work / "raw" / "kokoro-speech"
    zpath = download(KSD_ZIP, raw / "kokoro-speech-v1_3.zip")
    if hashlib.sha256(zpath.read_bytes()).hexdigest() != KSD_ZIP_SHA256:
        raise SystemExit(f"sha256 mismatch: {zpath}")
    with zipfile.ZipFile(zpath) as z:
        books = {b["id"]: b for b in json.loads(z.read("index.json"))}
        clips = []
        for book in sorted(books):
            for line in z.read(f"{book}.metadata.txt").decode("utf-8").splitlines():
                cid, mp3, start, end, text, _reading = line.split("|")
                clips.append((cid, book, mp3, int(start), int(end), text))
    picked = sorted(random.Random(SEED).sample(clips, n))
    rows, decoded = [], {}
    for cid, book, mp3, start, end, text in picked:
        dest = raw / "clips" / f"{cid}.wav"
        if not dest.exists():
            # archive_url is the book's zip, ".../download/<item>/<item>_64kb_mp3.zip"; files sit beside it.
            item = books[book]["archive_url"].split("/download/")[1].strip("/").split("/")[0]
            src = download(f"https://archive.org/download/{item}/{mp3}", raw / "mp3" / item / mp3)
            if src not in decoded:
                d = miniaudio.decode_file(str(src), output_format=miniaudio.SampleFormat.FLOAT32, nchannels=1,
                                          sample_rate=22_050)
                decoded = {src: np.asarray(d.samples, dtype=np.float32)}  # one file at a time
            dest.parent.mkdir(parents=True, exist_ok=True)
            write_float_wav(dest, decoded[src][start:end], sample_rate=22_050)
        # The Aozora text is tokenised with spaces (MeCab); Japanese has none.
        rows.append({"id": cid, "audio": str(dest), "text": text.replace(" ", ""), "lang": "ja"})
    write_manifest(work / "data" / "kokoro-speech-ja", rows)


SETS = {
    "ls-clean": lambda w: librispeech(w, "ls-clean"),
    "ls-other": lambda w: librispeech(w, "ls-other"),
    "fleurs-en": lambda w: fleurs(w, "fleurs-en"),
    "fleurs-es": lambda w: fleurs(w, "fleurs-es"),
    "fleurs-de": lambda w: fleurs(w, "fleurs-de"),
    "fleurs-fr": lambda w: fleurs(w, "fleurs-fr"),
    "fleurs-ja": lambda w: fleurs(w, "fleurs-ja"),
    "fleurs-zh": lambda w: fleurs(w, "fleurs-zh"),
    "fleurs-ko": lambda w: fleurs(w, "fleurs-ko"),
    **{f"fleurs-{x}": (lambda x: lambda w: fleurs(w, f"fleurs-{x}"))(x)
       for x in ("hi", "ar", "tr", "vi", "nb", "it", "pt")},
    **{f"vox-{x}": (lambda x: lambda w: voxpopuli(w, f"vox-{x}"))(x) for x in ("de", "es", "fr", "it", "en")},
    "ami-ihm": ami,
    "ami-long": lambda w: ami(w, "ami-long", min_seconds=8.0),
    "ami-multi": ami_multi,
    "aishell1": aishell1,
    "zeroth-ko": zeroth,
    "kokoro-speech-ja": kokoro_speech,
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", type=Path, required=True)
    ap.add_argument("sets", nargs="*", help=f"default: all of {', '.join(SETS)}")
    args = ap.parse_args()
    for s in args.sets or SETS:
        SETS[s](args.work)


if __name__ == "__main__":
    main()
